import assert from 'node:assert/strict';
import * as THREE from 'three';
import { PondApp } from '../js/core/app.js';
import { createTree } from '../js/generators/tree.js';
import { DEFAULTS } from '../js/config/index.js';

const app = Object.create(PondApp.prototype);
const sceneryMaterial = new THREE.MeshBasicMaterial();
const antMaterial = new THREE.MeshBasicMaterial();
const scenery = new THREE.Mesh(new THREE.BoxGeometry(), sceneryMaterial);
const ant = new THREE.Group();
ant.add(new THREE.Mesh(new THREE.BoxGeometry(), antMaterial));
app.world = new THREE.Group();
app.world.add(scenery, ant);
app.ant = { group: ant };
app.tree = { group: scenery };
app.modelProps = { ant: app.ant };
app.antOcclusionCandidates = [];
app.antOcclusionRockSources = new Map();
app.antOcclusionMaterials = [];
app.antOcclusionActive = [];
app.antOcclusionUniforms = { center: { value: new THREE.Vector2() }, radius: { value: 0 }, depth: { value: 0 } };
app.setupAntOcclusionWindow();
assert.deepEqual(app.antOcclusionCandidates, [scenery], 'Only scenery is considered an obstruction.');
const entry = app.getAntOcclusionMaterial(scenery);
assert.equal(ant.children[0].material, antMaterial);
assert.equal(entry.faded.transparent, true);
const shader = { uniforms: {}, fragmentShader: 'void main() {\n#include <opaque_fragment>\n}' };
entry.faded.onBeforeCompile(shader, {});
assert.match(shader.fragmentShader, /smoothstep/);
assert.match(shader.fragmentShader, /diffuseColor\.a \*=/);
assert.match(shader.fragmentShader, /gl_FragCoord\.z < antWindowDepth/);
assert.doesNotMatch(shader.fragmentShader, /discard|antWindowNoise/);
scenery.material = entry.faded;
app.antOcclusionActive = [entry];
app.setAntOcclusionEnabled(false);
assert.equal(scenery.material, sceneryMaterial, 'Turning the setting off restores the obstruction.');
const second = new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshBasicMaterial());
scenery.position.z = -2;
second.position.z = -3;
ant.position.z = -5;
app.world.add(second);
app.modelProps.second = { group: second };
app.antOcclusionCandidates = [];
app.setupAntOcclusionWindow();
app.world.updateMatrixWorld(true);
app.camera = new THREE.PerspectiveCamera(50, 1, 0.1, 100);
app.camera.updateMatrixWorld(true);
app.isAntViewActive = () => true;
app.antOcclusionRaycaster = new THREE.Raycaster();
app.antOcclusionLowRaycaster = new THREE.Raycaster();
app.antOcclusionLowDirection = new THREE.Vector3();
app.antOcclusionDirection = new THREE.Vector3();
app.antOcclusionBox = new THREE.Box3();
app.antOcclusionProbe = new THREE.Vector3();
app.antOcclusionPosition = new THREE.Vector3();
app.antOcclusionSize = new THREE.Vector2();
app.antOcclusionHits = [];
app.clock = { getElapsed: () => 1 };
app.renderer = { getDrawingBufferSize: (target) => target.set(800, 800), getPixelRatio: () => 1 };
app.setAntOcclusionEnabled(true);
app.updateAntOcclusionWindow();
assert.equal(app.antOcclusionActive.length, 2, 'Overlapping obstructions must both fade.');
assert.notEqual(scenery.material, sceneryMaterial);
assert.notEqual(second.material, app.antOcclusionActive.find((item) => item.mesh === second).original);
assert.ok(app.antOcclusionUniforms.radius.value > 0);
app.setAntOcclusionEnabled(false);
assert.equal(scenery.material, sceneryMaterial);
assert.equal(app.antOcclusionActive.length, 0);
// The camera can be inside the tree's overall bounds while a root is in front of the ant.
const tree = createTree(DEFAULTS);
app.world = new THREE.Group();
app.world.add(tree.group, ant);
ant.position.set(1.075, 0.185, 1.497);
app.world.updateMatrixWorld(true);
app.tree = tree;
app.modelProps = { ant: app.ant };
app.antOcclusionCandidates = [];
app.setupAntOcclusionWindow();
app.camera.position.set(2.575, 0.665, 1.316);
app.camera.lookAt(1.075, 0.220, 1.497);
app.camera.updateMatrixWorld(true);
app.setAntOcclusionEnabled(true);
app.updateAntOcclusionWindow();
assert.ok(app.antOcclusionActive.some((entry) => entry.mesh === tree.woodMesh),
  'The root must be detected when the camera is inside the tree bounds.');
app.setAntOcclusionEnabled(false);
tree.group.userData.dispose();
// Aggregate rock bounds can cover the camera and player even when every rock is to the side.
const rocks = new THREE.InstancedMesh(new THREE.BoxGeometry(), new THREE.MeshBasicMaterial(), 3);
const matrix = new THREE.Matrix4();
rocks.setMatrixAt(0, matrix.makeTranslation(1.5, 0.07, -2));
rocks.setMatrixAt(1, matrix.makeTranslation(-1.5, 0.07, -2));
rocks.setMatrixAt(2, matrix.makeTranslation(0, 0.07, -7));
const anchors = [
  { rockIndex: 0, position: { x: 1.5, z: -2 }, usableRadius: 0.5 },
  { rockIndex: 1, position: { x: -1.5, z: -2 }, usableRadius: 0.5 },
  { rockIndex: 2, position: { x: 0, z: -7 }, usableRadius: 0.5 },
];
app.world = new THREE.Group();
app.world.add(rocks, ant);
ant.position.set(0, 0, -5);
app.world.updateMatrixWorld(true);
app.tree = null;
app.modelProps = { ant: app.ant };
app.ground = { rockSurfaceMesh: rocks, rockSurfaceAnchors: anchors };
app.antOcclusionCandidates = [];
app.antOcclusionInstanceProxy = new THREE.Mesh();
app.antOcclusionInstanceProxy.matrixAutoUpdate = false;
app.antOcclusionInstanceMatrix = new THREE.Matrix4();
app.setupAntOcclusionWindow();
app.camera.position.set(0, 0.07, 0);
app.camera.lookAt(0, 0.07, -5);
app.camera.updateMatrixWorld(true);
app.setAntOcclusionEnabled(true);
app.updateAntOcclusionWindow();
assert.equal(app.antOcclusionActive.length, 0, 'Side and background rocks must remain opaque.');
rocks.setMatrixAt(0, matrix.makeTranslation(0, 0.07, -2));
anchors[0].position.x = 0;
app.setAntOcclusionEnabled(true);
app.updateAntOcclusionWindow();
assert.ok(app.antOcclusionActive.some((item) => item.mesh === rocks),
  'A rock actually between the camera and ant must fade.');
app.setAntOcclusionEnabled(false);
// Low shoreline stones can cover the ant's feet while the center ray passes overhead.
const shore = new THREE.InstancedMesh(new THREE.BoxGeometry(), new THREE.MeshBasicMaterial(), 1);
shore.setMatrixAt(0, matrix.makeScale(0.5, 0.02, 0.5).setPosition(0, 0.014, -4));
app.world = new THREE.Group();
app.world.add(shore, ant);
app.world.updateMatrixWorld(true);
app.ground = { pondRockSurfaceMesh: shore, pondRockSurfaceAnchors: [
  { rockIndex: 0, position: { x: 0, z: -4 }, usableRadius: 0.25 },
] };
app.antOcclusionCandidates = [];
app.setupAntOcclusionWindow();
app.setAntOcclusionEnabled(true);
app.updateAntOcclusionWindow();
assert.ok(app.antOcclusionActive.some((item) => item.mesh === shore),
  'A low pond rock in front of the ant must be detected.');
app.setAntOcclusionEnabled(false);
// Reader materials are already transparent for the day/night routine.
const readerMaterial = new THREE.MeshBasicMaterial({ transparent: true, opacity: 0.8 });
const readerMesh = new THREE.Mesh(new THREE.BoxGeometry(), readerMaterial);
const readerGroup = new THREE.Group();
readerGroup.position.z = -2;
readerGroup.add(readerMesh);
const readerProxy = new THREE.Group();
readerProxy.position.z = -2;
readerProxy.add(new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshBasicMaterial()));
app.world = new THREE.Group();
app.world.add(readerGroup, readerProxy, ant);
app.world.updateMatrixWorld(true);
app.reader = { group: readerGroup };
app.readerSurfaceProxy = readerProxy;
app.readerNightBlend = 0;
app.ground = null;
app.modelProps = { ant: app.ant, reader: app.reader };
app.antOcclusionCandidates = [];
app.setupAntOcclusionWindow();
app.setAntOcclusionEnabled(true);
app.updateAntOcclusionWindow();
assert.ok(app.antOcclusionActive.some((item) => item.mesh === readerMesh),
  'The reader proxy must activate the fade on already-transparent reader materials.');
readerMaterial.opacity = 0.4;
app.updateAntOcclusionWindow();
assert.equal(readerMesh.material.opacity, 0.4, 'The reader night fade must continue to update.');
app.setAntOcclusionEnabled(false);
assert.equal(readerMesh.material, readerMaterial);
console.log('Ant visibility checks passed: smooth scenery fade, intact ant material, and immediate setting reset.');
const burrow = new THREE.Group();
const roofMaterial = new THREE.MeshStandardMaterial();
const roof = new THREE.Mesh(new THREE.BoxGeometry(), roofMaterial); burrow.add(roof);
app.world.add(burrow);
app.addGameOcclusionRoot(burrow); app.addGameOcclusionRoot(burrow);
assert.equal(app.antOcclusionCandidates.filter((mesh) => mesh === roof).length, 1);
const roofFade = app.getAntOcclusionMaterial(roof);
roof.material = roofFade.faded; app.antOcclusionActive.push(roofFade);
let roofDisposals = 0; roofFade.clones.forEach((material) => material.addEventListener('dispose', () => roofDisposals++));
app.removeGameOcclusionRoot(burrow);
assert.equal(roof.material, roofMaterial);
assert.ok(!app.antOcclusionCandidates.includes(roof));
assert.ok(!app.antOcclusionActive.includes(roofFade));
assert.equal(roofDisposals, roofFade.clones.length);
